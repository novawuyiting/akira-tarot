const cart = [];
let currentLang = "zh";
let currentLesson = "majors";
let currentCardIndex = 0;
let currentNoteKey = "";

const cardName = document.querySelector("#cardName");
const cardMeaning = document.querySelector("#cardMeaning");
const tarotButtons = document.querySelectorAll(".tarot-card");
const resetDraw = document.querySelector("#resetDraw");
const tabs = document.querySelectorAll(".tab");
const lessonKicker = document.querySelector("#lessonKicker");
const lessonTitle = document.querySelector("#lessonTitle");
const lessonCopy = document.querySelector("#lessonCopy");
const sessionSelect = document.querySelector("#sessionSelect");
const cartItems = document.querySelector("#cartItems");
const cartTotal = document.querySelector("#cartTotal");
const formNote = document.querySelector("#formNote");
const languageButtons = document.querySelectorAll(".language-option");

function t(key) {
  return translations[currentLang][key];
}

function setText(key, value) {
  document.querySelectorAll(`[data-i18n="${key}"]`).forEach((node) => {
    node.textContent = value;
  });
}

function populateSessions(selectedKey = sessionSelect.dataset.selectedKey || "reading30") {
  sessionSelect.innerHTML = "";
  sessionOrder.forEach((key) => {
    const option = document.createElement("option");
    option.value = serviceValues[currentLang][key];
    option.textContent = serviceValues[currentLang][key];
    option.dataset.serviceKey = key;
    sessionSelect.append(option);
  });
  setSessionByKey(selectedKey);
}

function setSessionByKey(key) {
  sessionSelect.dataset.selectedKey = key;
  sessionSelect.value = serviceValues[currentLang][key];
}

function renderLesson() {
  const [kicker, title, copy] = lessons[currentLang][currentLesson];
  lessonKicker.textContent = kicker;
  lessonTitle.textContent = title;
  lessonCopy.textContent = copy;
}

function renderCard() {
  const [name, meaning] = cards[currentLang][currentCardIndex];
  cardName.textContent = name;
  cardMeaning.textContent = meaning;
}

function renderCart() {
  if (cart.length === 0) {
    cartItems.innerHTML = `<li>${t("cartEmpty")}</li>`;
    cartTotal.textContent = t("cartMethodDefault");
    return;
  }

  cartItems.innerHTML = cart.map((key) => `<li>${productValues[currentLang][key]}</li>`).join("");
  cartTotal.textContent = t("cartMethodSelected");
}

function renderNote() {
  if (!currentNoteKey) {
    formNote.textContent = "";
    return;
  }

  if (currentNoteKey === "selectedProducts") {
    formNote.textContent = `${t("selectedProductsPrefix")}${cart
      .map((key) => productValues[currentLang][key])
      .join(currentLang === "zh" ? "、" : ", ")}${t("selectedProductsSuffix")}`;
    return;
  }

  formNote.textContent = t(currentNoteKey);
}

function setLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

  Object.entries(translations[currentLang]).forEach(([key, value]) => {
    setText(key, value);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === currentLang;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  populateSessions();
  renderLesson();
  renderCard();
  renderCart();
  renderNote();
}

function revealCard(button) {
  currentCardIndex = Math.floor(Math.random() * cards[currentLang].length);
  tarotButtons.forEach((item) => item.classList.remove("revealed"));
  button.classList.add("revealed");
  renderCard();
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

tarotButtons.forEach((button) => {
  button.addEventListener("click", () => revealCard(button));
});

resetDraw.addEventListener("click", () => {
  tarotButtons.forEach((button) => button.classList.remove("revealed"));
  revealCard(tarotButtons[Math.floor(Math.random() * tarotButtons.length)]);
});

tabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    currentLesson = tab.dataset.lesson;
    tabs.forEach((item) => {
      item.classList.remove("active");
      item.setAttribute("aria-selected", "false");
    });
    tab.classList.add("active");
    tab.setAttribute("aria-selected", "true");
    renderLesson();
  });
});

document.querySelectorAll("[data-service-key]").forEach((link) => {
  link.addEventListener("click", () => {
    setSessionByKey(link.dataset.serviceKey);
  });
});

sessionSelect.addEventListener("change", () => {
  const selectedOption = sessionSelect.options[sessionSelect.selectedIndex];
  sessionSelect.dataset.selectedKey = selectedOption.dataset.serviceKey;
});

document.querySelectorAll(".product-button").forEach((button) => {
  button.addEventListener("click", () => {
    cart.push(button.dataset.productKey);
    currentNoteKey = "";
    renderCart();
    renderNote();
  });
});

document.querySelector("#checkoutButton").addEventListener("click", () => {
  if (cart.length === 0) {
    currentNoteKey = "chooseCardFirst";
    renderNote();
    document.querySelector("#shop").scrollIntoView({ behavior: "smooth" });
    return;
  }

  setSessionByKey("cards");
  currentNoteKey = "selectedProducts";
  renderNote();
  document.querySelector("#booking").scrollIntoView({ behavior: "smooth" });
});

document.querySelector(".booking-form").addEventListener("submit", (event) => {
  event.preventDefault();
  currentNoteKey = "bookingSubmitted";
  renderNote();
});

setLanguage("zh");
